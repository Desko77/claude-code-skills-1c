# --- Стадии ---

def _parse_speaker_map(resp):
    """Ответ модели -> {метка: имя}. Понимает обе формы: массив по схеме SPEAKERS_SCHEMA и
    плоский объект {"SPEAKER_00": "имя"} - движки без строгих схем отвечают вторым."""
    try:
        m = re.search(r"\{.*\}", resp, re.S)
        data = json.loads(m.group(0)) if m else {}
    except (json.JSONDecodeError, ValueError, AttributeError, TypeError):
        return {}
    if isinstance(data.get("speakers"), list):
        return {str(it.get("label")): str(it.get("name")) for it in data["speakers"]
                if isinstance(it, dict) and it.get("label") and it.get("name")}
    return {str(k): str(v) for k, v in data.items()
            if v and isinstance(v, str) and str(v) != str(k)}


def map_speakers(transcript_text, llm, max_chars=48000, voice_confirmed=(), log=None,
                 validate=True):
    """Определить имена спикеров по репликам. Возвращает {метка: имя} (пустой при неудаче).

    Ответ модели ОБЯЗАТЕЛЬНО проходит программную проверку (speaker_validator): все проверенные
    модели систематически вешают имя на того, кто его произносит, а не на адресата, и правило в
    промпте это не лечит. Проверка перевешивает такие имена на отвечающую метку, снимает роли и
    заглушки, сводит усеченные формы к полной и не дает одному имени висеть на двух метках.

    voice_confirmed - метки, чье имя уже подтверждено голосовой базой: их проверка не трогает,
    голос надежнее текстовых улик. log - куда писать отчет о правках (например print).

    max_chars большой, чтобы охватить весь транскрипт: имена часто звучат ближе к концу.
    """
    if not transcript_text.strip():
        return {}
    try:
        resp = llm(transcript_text[:max_chars], PROMPT_SPEAKERS)
        names = _parse_speaker_map(resp)
    except Exception as e:   # модель недоступна или ответила мусором - улики из речи все равно есть
        names = {}
        if log:
            log(f"текстовый слой не ответил ({e}) - опираюсь только на разбор обращений")
    if not validate:
        return names
    fixed, report = sv.validate(names, transcript_text, voice_confirmed=voice_confirmed)
    if log:
        for line in report:
            log(f"проверка имен: {line}")
    return fixed


def apply_names(text, name_map):
    """Заменить метки спикеров на имена ОДНИМ проходом (комбинированный regex, подстановка по словарю).

    Один проход, а не цепочка re.sub: уже подставленное имя НЕ может быть повторно перезаписано
    следующей меткой. Это устраняет каскадное схлопывание, если LLM перепутал метки местами (напр.
    вернул SPEAKER_00->SPEAKER_01): при последовательных re.sub речь двух спикеров склеилась бы в одно
    имя. Метки в альтернации длинными первыми (SPEAKER_00 матчится раньше SPEAKER_0)."""
    if not name_map or not text:
        return text
    labels = sorted(name_map, key=len, reverse=True)
    pattern = re.compile("|".join(re.escape(lbl) for lbl in labels))
    return pattern.sub(lambda m: name_map[m.group(0)], text)


def _split_frame_blocks(mechanical_log):
    """Разбить механический лог на блоки-кадры (граница - строка, начинающаяся с '## [' или '[MM:SS]')."""
    blocks = re.split(r"(?=^#{0,3}\s*\[\d{1,2}:\d{2}\])", mechanical_log, flags=re.M)
    return [b for b in blocks if b.strip()]


# Числа и коды: то, что модель обязана переносить дословно и на чем она чаще всего сочиняет.
# Токен - последовательность из цифр, букв, точек, запятых и дефисов, содержащая хотя бы одну цифру.
_NUM_TOKEN = re.compile(r"[A-Za-zА-Яа-я0-9]+(?:[.,\-/][A-Za-zА-Яа-я0-9]+)*")
_TIMECODE = re.compile(r"^\d{1,3}:\d{2}(:\d{2})?$")


def _number_tokens(text):
    """Числа/коды текста в нормализованном виде: {как сравнивать: как выглядит в тексте}.

    Разряды числа склеиваются до разбора (1 234,56 и 1234,56 - одно и то же), регистр не
    учитывается, таймкоды отбрасываются (они - разметка нарратива, а не данные с экрана).
    """
    text = re.sub(r"(?<=\d)[\s ](?=\d)", "", text)
    out = {}
    for m in _NUM_TOKEN.finditer(text):
        raw = m.group(0).strip(".,-/")
        if len(raw) < 3 or not any(c.isdigit() for c in raw) or _TIMECODE.match(raw):
            continue
        out.setdefault(raw.lower(), raw)
    return out


def unsupported_numbers(narrative, source):
    """Числа и коды нарратива, которых нет в исходном материале. Список того, что модель сочинила.

    Проверка нужна ровно потому, что запрет в промпте не держит: на реальном прогоне модель выдала
    коды счетов и диапазоны кодов, которых в описаниях кадров не было. Молча вырезать их нельзя -
    можно порвать фразу, поэтому находки выносятся в отчет, а решение остается за человеком.
    """
    src = _number_tokens(source)
    return [raw for key, raw in _number_tokens(narrative).items() if key not in src]


def build_coherent_log(mechanical_log, llm, chunk_chars=18000, report=None):
    """Связный нарратив из механической склейки (экран+речь). Чанкуем под контекст модели.

    Каждый чанк - несколько кадров подряд; на выходе нарративы конкатенируются по порядку.
    report - список, куда дописываются строки о числах, не подтвержденных исходным материалом
    (по одной на чанк). Передавать необязательно: без него проверка просто не ведется.
    """
    blocks = _split_frame_blocks(mechanical_log)
    if not blocks:
        return ""
    chunks, cur, cur_len = [], [], 0
    for b in blocks:
        if cur and cur_len + len(b) > chunk_chars:
            chunks.append("".join(cur))
            cur, cur_len = [], 0
        cur.append(b)
        cur_len += len(b)
    if cur:
        chunks.append("".join(cur))

    out = []
    for i, ch in enumerate(chunks, 1):
        narrative = llm(ch, PROMPT_COHERENT).strip()
        if not narrative:
            continue
        out.append(narrative)
        if report is not None:
            bad = unsupported_numbers(narrative, ch)
            if bad:
                report.append(f"фрагмент {i} из {len(chunks)}: {', '.join(bad)}")
    return "\n\n".join(out)


def _chunk_by_lines(text, chunk_chars):
    """Разбить текст на чанки ~chunk_chars по границам строк (строки не рвем)."""
    chunks, cur, cur_len = [], [], 0
    for ln in text.splitlines(keepends=True):
        if cur and cur_len + len(ln) > chunk_chars:
            chunks.append("".join(cur))
            cur, cur_len = [], 0
        cur.append(ln)
        cur_len += len(ln)
    if cur:
        chunks.append("".join(cur))
    return chunks


def build_summary(transcript_text, llm, chunk_chars=40000, max_ctx_chars=80000):
    """2-проходное саммари с защитой от переполнения контекста на длинных встречах (H1).

    Проход 1 (факты): транскрипт длиннее chunk_chars извлекаем ПО ЧАНКАМ и склеиваем, чтобы длинная
    встреча не обрезалась в одном вызове. Короткая - как раньше, одним вызовом.
    Проход 2 (протокол): если транскрипт+факты влезают (<= max_ctx_chars) - подаем оба (контекст +
    контроль полноты); иначе (очень длинная встреча) - ТОЛЬКО факты (они и есть полный экстракт),
    иначе модель тихо обрежет середину. Пороги под контекст gemma (~32K); типичная встреча
    (<= chunk_chars, напр. 48-мин ~33K символов) идет одним проходом как раньше - без регресса."""
    if not transcript_text.strip():
        return None
    if len(transcript_text) <= chunk_chars:
        facts = llm(transcript_text, PROMPT_TASKS_EXTRACT)
    else:
        parts = []
        for ch in _chunk_by_lines(transcript_text, chunk_chars):
            f = llm(ch, PROMPT_TASKS_EXTRACT)
            if f and f.strip():
                parts.append(f.strip())
        facts = "\n\n".join(parts)
    if not facts or not facts.strip():
        return None
    if len(transcript_text) + len(facts) <= max_ctx_chars:
        data = (f"ТРАНСКРИПЦИЯ:\n\n{transcript_text}\n\n"
                f"---\n\nПРЕДВАРИТЕЛЬНО ИЗВЛЕЧЕННЫЕ ФАКТЫ:\n\n{facts}")
    else:
        data = ("ПОЛНЫЙ СПИСОК ИЗВЛЕЧЕННЫХ ФАКТОВ (задачи/решения/вопросы). Транскрипт слишком "
                "длинный для контекста - синтезируй протокол строго по этим фактам:\n\n" + facts)
    return llm(data, PROMPT_SUMMARY_FROM_TEXT)
